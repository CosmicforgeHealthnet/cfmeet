"""Operator notifications for the CF Meet TLS certificate monitor (GitHub Actions runner).

Input: the status the installed monitor printed on the VPS (`certificate_monitor.py
--check`) and the certificate that api.cfmeet.com presents publicly, as seen from the
runner. Destination: one tracking issue in this repository. Its body mentions the
owner account, so GitHub notifies them of every comment. A comment is posted when the
state changes (status, band, certificate, presentation), every day while ALERT, and on
a requested delivery test. Each comment is read back by id before delivery is
reported. Nothing secret is posted: fingerprints, dates and status words only.
"""
import json
import os
import sys
import urllib.error
import urllib.request

TITLE = 'Operations: api.cfmeet.com TLS certificate monitoring'
MARKER = '<!-- cfmeet-cert-state: %s -->'


def state_key(status, external):
    return '|'.join(str(x) for x in (status.get('status'), status.get('band'), status.get('managedFingerprint'),
                                     status.get('presentedMatchesManaged'), external.get('matchesManaged')))


def effective_status(status, external):
    """ALERT also when the public certificate is not the managed one or unreadable."""
    if status.get('status') not in ('OK', 'WARN', 'ALERT'):
        return 'ALERT'
    if not external.get('matchesManaged'):
        return 'ALERT'
    return status['status']


def last_state(comments):
    for c in reversed(comments):
        body = c.get('body') or ''
        start = body.find('<!-- cfmeet-cert-state: ')
        if start >= 0:
            return body[start + len('<!-- cfmeet-cert-state: '):body.find(' -->', start)]
    return None


def should_post(status, external, comments, delivery_test):
    if delivery_test:
        return True, 'delivery test'
    if effective_status(status, external) == 'ALERT':
        return True, 'alert (repeated daily while it lasts)'
    if last_state(comments) != state_key(status, external):
        return True, 'state changed'
    return False, 'unchanged'


def comment_body(status, external, reason, run_url):
    eff = effective_status(status, external)
    rows = ['| Target | Presents managed certificate | Stable handshakes | Reload attempts | Recovered |', '|---|---|---|---|---|']
    for t in status.get('targets', []):
        rows.append('| %s | %s | %s | %s | %s |' % (t['name'], 'yes' if t['matchesManaged'] else '**no**',
                                                     t['handshakes'] if t['stable'] else 'unstable', t['reloadAttempts'],
                                                     t['recovered'] or '-'))
    rows.append('| public api.cfmeet.com:443 (from GitHub) | %s | - | - | - |' % ('yes' if external.get('matchesManaged') else '**no**'))
    lines = ['**%s** — %s' % (eff, reason), '',
             '- Certificate: `%s`' % (status.get('managedFingerprint') or 'unreadable'),
             '- Expires: %s (%s days left, band: %s; warn at 45/30, alert at 14/7)' % (
                 status.get('expiresAt'), status.get('remainingDays'), status.get('band') or 'none'),
             '- Lineage problem: %s' % (status.get('problem') or 'none'),
             '- Checked: %s · run: %s' % (status.get('checkedAt'), run_url), ''] + rows
    if eff == 'ALERT':
        lines += ['', 'Runbook: docs/operations/tls-certificate-automation.md (renewal, activation, rollback).']
    return ('\n'.join(lines) + '\n\n' + MARKER % state_key(status, external) +
            '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_\n')


class GitHub:
    def __init__(self, repo, token, api='https://api.github.com'):
        self.repo, self.token, self.api = repo, token, api

    def call(self, method, path, body=None):
        req = urllib.request.Request(self.api + path, method=method,
                                     data=json.dumps(body).encode() if body is not None else None,
                                     headers={'Authorization': 'Bearer ' + self.token, 'Accept': 'application/vnd.github+json',
                                              'X-GitHub-Api-Version': '2022-11-28', 'User-Agent': 'cfmeet-certificate-monitor'})
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read() or b'null')

    def tracking_issue(self, owner_login):
        for page in range(1, 6):
            for issue in self.call('GET', '/repos/%s/issues?state=open&per_page=100&page=%d' % (self.repo, page)):
                if issue.get('title') == TITLE and 'pull_request' not in issue:
                    return issue
        body = ('Automated TLS certificate monitoring for `api.cfmeet.com` (private proxy and host nginx), posted by '
                'the scheduled workflow `cfmeet-certificate-monitor.yml`.\n\nOperator: @%s. Comments arrive on state changes, '
                'daily while ALERT, and for delivery tests. Warn at 45/30 days, alert at 14/7 days, expiry, an invalid '
                'lineage, or a proxy not presenting the managed certificate.\n\nKeep this issue open: it is the delivery '
                'destination.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' % owner_login)
        return self.call('POST', '/repos/%s/issues' % self.repo, {'title': TITLE, 'body': body})

    def comments(self, number):
        return self.call('GET', '/repos/%s/issues/%d/comments?per_page=100' % (self.repo, number))

    def post(self, number, body):
        return self.call('POST', '/repos/%s/issues/%d/comments' % (self.repo, number), {'body': body})

    def read_comment(self, comment_id):
        return self.call('GET', '/repos/%s/issues/comments/%d' % (self.repo, comment_id))


def notify(gh, status, external, delivery_test, run_url, owner_login):
    issue = gh.tracking_issue(owner_login)
    comments = gh.comments(issue['number'])
    post, reason = should_post(status, external, comments, delivery_test)
    result = {'issue': issue['html_url'], 'status': effective_status(status, external), 'posted': False, 'reason': reason}
    if post:
        body = comment_body(status, external, reason, run_url)
        created = gh.post(issue['number'], body)
        echoed = gh.read_comment(created['id'])
        result.update(posted=True, comment=created['html_url'],
                      delivered=echoed.get('id') == created['id'] and (MARKER % state_key(status, external)) in echoed.get('body', ''))
    return result


def main(argv):
    status = json.loads(open(argv[0]).read() or '{}')
    external = json.loads(open(argv[1]).read() or '{}')
    external['matchesManaged'] = bool(external.get('fingerprint')) and external.get('fingerprint') == status.get('managedFingerprint')
    gh = GitHub(os.environ['GITHUB_REPOSITORY'], os.environ['GITHUB_TOKEN'])
    run_url = '%s/%s/actions/runs/%s' % (os.environ.get('GITHUB_SERVER_URL', 'https://github.com'),
                                         os.environ['GITHUB_REPOSITORY'], os.environ.get('GITHUB_RUN_ID', ''))
    result = notify(gh, status, external, os.environ.get('DELIVERY_TEST') == 'true', run_url,
                    os.environ.get('OPERATOR_LOGIN', os.environ['GITHUB_REPOSITORY'].split('/')[0]))
    print(json.dumps(result))
    if result['posted'] and not result.get('delivered'):
        print('NOTIFICATION_NOT_DELIVERED'); return 2
    if result['posted']:
        print('NOTIFICATION_DELIVERED:', result['comment'])
    # A red scheduled run is a second, independent signal while the certificate needs attention.
    return 1 if result['status'] == 'ALERT' else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
