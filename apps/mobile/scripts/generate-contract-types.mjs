#!/usr/bin/env node
/**
 * Generates `lib/api/generated/meeting-service.ts` from the served Meeting Service contract
 * (`packages/contracts/openapi/meeting-service.json`, OpenAPI 3.0).
 *
 * Every request/response DTO the mobile app sends or reads is a type alias of a generated
 * schema, so a contract change that the app does not follow fails `tsc` instead of failing on
 * a device (MTG-001 / MTG-003). The output is committed; `--check` (run by the unit tests and
 * Mobile CI) fails when it is stale.
 *
 *   node scripts/generate-contract-types.mjs          # write
 *   node scripts/generate-contract-types.mjs --check  # verify, exit 1 when stale
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const CONTRACT_PATH = resolve(here, "../../../packages/contracts/openapi/meeting-service.json");
export const OUTPUT_PATH = resolve(here, "../lib/api/generated/meeting-service.ts");

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function refName(ref) {
  const prefix = "#/components/schemas/";
  if (!ref.startsWith(prefix)) throw new Error(`unsupported $ref ${ref}`);
  return ref.slice(prefix.length);
}

function literal(value) {
  return JSON.stringify(value);
}

function typeOf(schema, indent) {
  if (!schema || typeof schema !== "object") return "unknown";
  let t = baseType(schema, indent);
  if (schema.nullable) t = `${t} | null`;
  return t;
}

function baseType(schema, indent) {
  if (schema.$ref) return refName(schema.$ref);
  if (schema.allOf) {
    const parts = schema.allOf.map((s) => typeOf(s, indent));
    return parts.length === 1 ? parts[0] : parts.map((p) => `(${p})`).join(" & ");
  }
  if (schema.oneOf || schema.anyOf) {
    return (schema.oneOf || schema.anyOf).map((s) => `(${typeOf(s, indent)})`).join(" | ");
  }
  if (schema.enum) return schema.enum.map(literal).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `Array<${typeOf(schema.items, indent)}>`;
    case "object":
    case undefined:
      return objectType(schema, indent);
    default:
      return "unknown";
  }
}

function objectType(schema, indent) {
  const props = schema.properties ?? {};
  const required = new Set(schema.required ?? []);
  const keys = Object.keys(props).sort();
  const pad = "  ".repeat(indent + 1);
  const lines = keys.map((key) => {
    const name = IDENT.test(key) ? key : literal(key);
    const opt = required.has(key) ? "" : "?";
    return `${pad}${name}${opt}: ${typeOf(props[key], indent + 1)};`;
  });
  const extra = schema.additionalProperties;
  if (extra && typeof extra === "object") {
    lines.push(`${pad}[key: string]: ${typeOf(extra, indent + 1)};`);
  } else if (extra === true || (keys.length === 0 && extra !== false)) {
    lines.push(`${pad}[key: string]: unknown;`);
  }
  if (lines.length === 0) return "Record<string, never>";
  return `{\n${lines.join("\n")}\n${"  ".repeat(indent)}}`;
}

export function generate(contract) {
  const schemas = contract.components?.schemas ?? {};
  const out = [
    "/* eslint-disable */",
    "// GENERATED by apps/mobile/scripts/generate-contract-types.mjs from",
    "// packages/contracts/openapi/meeting-service.json — do not edit by hand.",
    `// Contract version ${contract.info?.version ?? "unknown"}; ${Object.keys(schemas).length} schemas.`,
    "",
  ];
  for (const name of Object.keys(schemas).sort()) {
    if (!IDENT.test(name)) throw new Error(`schema name ${name} is not a TS identifier`);
    out.push(`export type ${name} = ${typeOf(schemas[name], 0)};`, "");
  }
  return out.join("\n");
}

function main() {
  const contract = JSON.parse(readFileSync(CONTRACT_PATH, "utf8"));
  const text = generate(contract);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUTPUT_PATH, "utf8");
    } catch {
      // missing counts as stale
    }
    if (current.replace(/\r\n/g, "\n") !== text) {
      console.error(
        "lib/api/generated/meeting-service.ts is stale: run `node scripts/generate-contract-types.mjs`"
      );
      process.exit(1);
    }
    return;
  }
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true });
  writeFileSync(OUTPUT_PATH, text);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
