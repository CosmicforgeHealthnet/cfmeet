#!/usr/bin/env node
/**
 * Packages the browser crypto core (wasm-bindgen output of packages/messaging-crypto/wasm)
 * for apps/web: content-addressed file names, the worker with the module's SHA-384 pinned
 * inside it, a manifest, and the generated constant the app loads the worker from.
 *
 *   node scripts/package-messaging-crypto.mjs <wasm-bindgen out dir> write|check "<toolchain>"
 *
 * Run through scripts/messaging/build-web-crypto.sh (the reproducible build). `check`
 * fails unless the committed files are byte-identical to what the sources produce.
 */
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WEB = join(dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC_DIR = join(WEB, "public", "messaging-crypto");
const GENERATED_TS = join(WEB, "src", "lib", "messaging", "crypto-artifact.ts");
const WORKER_SRC = join(WEB, "messaging-crypto", "worker.src.js");
export const URL_PREFIX = "/messaging-crypto/";

const [, , outDir, mode = "write", toolchain = "unknown"] = process.argv;
if (!outDir || !["write", "check"].includes(mode)) {
  console.error("usage: package-messaging-crypto.mjs <out dir> write|check <toolchain>");
  process.exit(2);
}

const sha = (alg, b) => createHash(alg).update(b).digest();
const short = (b) => sha("sha256", b).toString("hex").slice(0, 16);
const sri = (b) => "sha384-" + sha("sha384", b).toString("base64");

const glue = readFileSync(join(outDir, "cf_messaging_crypto_wasm.js"));
const wasm = readFileSync(join(outDir, "cf_messaging_crypto_wasm_bg.wasm"));
const glueName = `cf-messaging-crypto.${short(glue)}.js`;
const wasmName = `cf-messaging-crypto.${short(wasm)}.wasm`;
const workerSource = readFileSync(WORKER_SRC, "utf8");
for (const token of ["__GLUE__", "__WASM__", "__WASM_SHA384__"]) {
  if (!workerSource.includes(token)) throw new Error(`worker.src.js lacks ${token}`);
}
const worker = Buffer.from(
  workerSource
    .replaceAll("__GLUE__", `./${glueName}`)
    .replaceAll("__WASM__", `./${wasmName}`)
    .replaceAll("__WASM_SHA384__", sha("sha384", wasm).toString("base64")),
);
const workerName = `crypto-worker.${short(worker)}.js`;
const manifest = Buffer.from(
  JSON.stringify(
    {
      version: 1,
      description:
        "CF Meet Messaging browser crypto core (packages/messaging-crypto/wasm). Rebuild and verify with scripts/messaging/build-web-crypto.sh --check.",
      toolchain,
      files: {
        [workerName]: { role: "worker", integrity: sri(worker), bytes: worker.length },
        [glueName]: { role: "glue", integrity: sri(glue), bytes: glue.length },
        [wasmName]: { role: "wasm", integrity: sri(wasm), bytes: wasm.length },
      },
    },
    null,
    2,
  ) + "\n",
);
const ts = Buffer.from(`// Generated by apps/web/scripts/package-messaging-crypto.mjs — do not edit.
// The content-addressed crypto worker (its module's SHA-384 is pinned inside it).
export const MESSAGING_CRYPTO_WORKER_URL = "${URL_PREFIX}${workerName}";
export const MESSAGING_CRYPTO_WORKER_INTEGRITY = "${sri(worker)}";
`);

const files = new Map([
  [join(PUBLIC_DIR, workerName), worker],
  [join(PUBLIC_DIR, glueName), glue],
  [join(PUBLIC_DIR, wasmName), wasm],
  [join(PUBLIC_DIR, "manifest.json"), manifest],
  [GENERATED_TS, ts],
]);

if (mode === "check") {
  const problems = [];
  for (const [path, bytes] of files) {
    if (!existsSync(path)) problems.push(`missing ${path}`);
    else if (!readFileSync(path).equals(bytes)) problems.push(`differs ${path}`);
  }
  const expected = new Set([...files.keys()].filter((p) => p.startsWith(PUBLIC_DIR)).map((p) => p.slice(PUBLIC_DIR.length + 1)));
  for (const name of existsSync(PUBLIC_DIR) ? readdirSync(PUBLIC_DIR) : []) {
    if (!expected.has(name)) problems.push(`unexpected ${join(PUBLIC_DIR, name)}`);
  }
  if (problems.length) {
    console.error("The committed browser crypto artifact is not what the sources build:\n  " + problems.join("\n  "));
    process.exit(1);
  }
  console.log(`browser crypto artifact verified: ${workerName}, ${glueName}, ${wasmName} (${toolchain})`);
} else {
  rmSync(PUBLIC_DIR, { recursive: true, force: true });
  mkdirSync(PUBLIC_DIR, { recursive: true });
  for (const [path, bytes] of files) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, bytes);
  }
  console.log(`wrote ${workerName}, ${glueName}, ${wasmName}`);
}
