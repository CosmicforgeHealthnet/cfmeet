/// Successful responses and the gateway's quota headers.
library;

/// The platform request quota headers of one response (`x-cf-quota-*`). Every field is
/// null when the gateway did not send it (routes without a quota, local stacks).
class QuotaInfo {
  const QuotaInfo({
    this.limitMinute,
    this.remainingMinute,
    this.resetSeconds,
    this.limitDay,
    this.window,
    this.level,
  });

  /// Parses the quota headers (names lower-case). Null when none is present.
  static QuotaInfo? fromHeaders(Map<String, String> headers) {
    int? number(String name) => int.tryParse(headers[name]?.trim() ?? '');
    final q = QuotaInfo(
      limitMinute: number('x-cf-quota-limit-minute'),
      remainingMinute: number('x-cf-quota-remaining-minute'),
      resetSeconds: number('x-cf-quota-reset'),
      limitDay: number('x-cf-quota-limit-day'),
      window: headers['x-cf-quota-window'],
      level: headers['x-cf-quota-level'],
    );
    return q.isEmpty ? null : q;
  }

  final int? limitMinute;
  final int? remainingMinute;

  /// Seconds until the minute window resets.
  final int? resetSeconds;
  final int? limitDay;

  /// The exhausted window on a QUOTA_EXCEEDED refusal (`minute` / `day`).
  final String? window;

  /// The level the quota applies at (e.g. environment).
  final String? level;

  bool get isEmpty =>
      limitMinute == null &&
      remainingMinute == null &&
      resetSeconds == null &&
      limitDay == null &&
      window == null &&
      level == null;

  @override
  String toString() =>
      'QuotaInfo(limitMinute: $limitMinute, remainingMinute: $remainingMinute, '
      'resetSeconds: $resetSeconds, limitDay: $limitDay, window: $window, level: $level)';
}

/// A successful (2xx) response.
class ApiResponse {
  const ApiResponse({
    required this.status,
    required this.body,
    required this.headers,
    required this.requestId,
    required this.correlationId,
    required this.idempotentReplayed,
    required this.quota,
    required this.idempotencyKey,
    required this.attempts,
  });

  final int status;

  /// The decoded JSON body (`Map`, `List`, scalar), the raw text of a non-JSON body, or
  /// null when the body is empty.
  final Object? body;

  /// Response headers, names lower-case (multiple values joined with `, `).
  final Map<String, String> headers;

  /// `x-request-id`: quote it to support.
  final String? requestId;
  final String? correlationId;

  /// `idempotent-replayed: true`: the server answered from a stored result of the same
  /// Idempotency-Key (the operation was NOT performed again).
  final bool idempotentReplayed;
  final QuotaInfo? quota;

  /// The Idempotency-Key sent (generated by the SDK when the caller gave none).
  final String? idempotencyKey;

  /// Number of HTTP attempts made (1 without retries).
  final int attempts;

  /// The body as a JSON object (throws [StateError] when it is not one).
  Map<String, dynamic> get json {
    final b = body;
    if (b is Map<String, dynamic>) return b;
    throw StateError('response body is not a JSON object');
  }

  @override
  String toString() =>
      'ApiResponse($status, requestId: $requestId, replayed: $idempotentReplayed)';
}
