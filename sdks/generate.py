#!/usr/bin/env python3
"""CF Meet SDK generator (Part VI Section 52).

Reads sdks/generation.json, packages/contracts/manifest.json, the generated public API
documents (packages/contracts/bundled/public/**) and the gateway route manifest
(infra/api-gateway/route-manifest.json) and emits, for the TypeScript and Dart SDKs:

  * the pinned contract catalogue (id, version, kind, path, lifecycle);
  * the operation catalogue: every PUBLIC_CUSTOMER operation the gateway routes, with its
    domain, method, path template, protocol, authentication modes, required scope, path /
    query / header parameters, body, Idempotency-Key requirement, cursor pagination and
    RETRY CLASS:
      SAFE         GET: retried on network errors, 408 / 429 / 502 / 503 / 504;
      IDEMPOTENT   PUT / DELETE, or a mutation carrying an Idempotency-Key: retried with
                   the SAME key on the same conditions;
      NO_RETRY     other mutations: retried only on 429 (a refusal: nothing was done);
      NEVER        paid telecom mutations (generation.json `paidTelecomOperations`): NEVER
                   retried automatically; an unknown outcome is surfaced to the caller,
                   who reconciles (e.g. replays the same Idempotency-Key deliberately).
  * TypeScript models (generation.json `typescript.models`): a namespace per public domain
    with a type per component schema and the typed parameters / response of every REST
    operation.

Rules enforced (exit 1 on violation):

  * every listed contract is registered in the manifest;
  * SDKs are generated from published contracts only: no `internal` contract and nothing
    owned by a service whose surface is not customer ingress;
  * no product-specific name (CosmicForge products use the same SDK as everyone else);
  * every operation of the route manifest is in exactly one public document, operation
    names are unique per domain, every paid telecom operation exists and is a mutation;
  * generated files are deterministic and current (`--check`).

Usage:  generate.py            regenerate
        generate.py --check    exit 1 if a generated file is missing or stale
Standard library only.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
PRODUCT_RE = re.compile(r"karryam|healthnet|cosmicforge", re.I)
HEADER = "GENERATED by sdks/generate.py from packages/contracts/manifest.json. Do not edit."


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def catalogue(config: dict, manifest: dict) -> tuple[list[dict], list[str]]:
    errors: list[str] = []
    by_id = {}
    for c in manifest["contracts"]:
        major = int(c["version"].split(".")[0])
        by_id[(c["id"], major)] = c
        by_id.setdefault(c["id"], c)
    out = []
    for cid in config["contracts"]:
        c = by_id.get(cid)
        if c is None:
            errors.append(f"{cid}: not registered in packages/contracts/manifest.json")
            continue
        if c["visibility"] != "public":
            errors.append(f"{cid}: SDKs are generated from public contracts only")
        if PRODUCT_RE.search(cid) or PRODUCT_RE.search(c["path"]):
            errors.append(f"{cid}: product-specific contract")
        if not (ROOT / "packages/contracts" / c["path"]).is_file():
            errors.append(f"{cid}: {c['path']} does not exist")
        out.append({k: c[k] for k in ("id", "version", "kind", "path", "lifecycle")})
    if len(set(config["contracts"])) != len(config["contracts"]):
        errors.append("a contract is listed twice")
    return out, errors


def typescript(cat: list[dict], status: str) -> str:
    lines = [f"// {HEADER}", "", f"export const SDK_STATUS = {json.dumps(status)} as const;", "",
             "export interface ContractRef {", "  readonly id: string;", "  readonly version: string;",
             "  readonly kind: 'openapi' | 'json-schema';", "  readonly path: string;",
             "  readonly lifecycle: 'experimental' | 'beta' | 'stable' | 'deprecated';", "}", "",
             "export const CONTRACTS: readonly ContractRef[] = ["]
    for c in cat:
        lines.append("  { " + ", ".join(f"{k}: {json.dumps(c[k])}" for k in ("id", "version", "kind", "path", "lifecycle")) + " },")
    lines += ["] as const;", ""]
    return "\n".join(lines)


def dart(cat: list[dict], status: str) -> str:
    q = lambda s: "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"
    lines = [f"// {HEADER}", "", f"const String sdkStatus = {q(status)};", "",
             "class ContractRef {", "  const ContractRef(this.id, this.version, this.kind, this.path, this.lifecycle);", "",
             "  final String id;", "  final String version;", "  final String kind;", "  final String path;",
             "  final String lifecycle;", "}", "", "const List<ContractRef> contracts = <ContractRef>["]
    for c in cat:
        lines.append(f"  ContractRef({q(c['id'])}, {q(c['version'])}, {q(c['kind'])}, {q(c['path'])}, {q(c['lifecycle'])}),")
    lines += ["];", ""]
    return "\n".join(lines)


PUBLIC_DOCS = ROOT / "packages/contracts/bundled/public"
ROUTE_MANIFEST = ROOT / "infra/api-gateway/route-manifest.json"
MUTATIONS = ("POST", "PUT", "PATCH", "DELETE")


def resolve(doc: dict, node):
    seen = 0
    while isinstance(node, dict) and "$ref" in node:
        ref = node["$ref"]
        if not ref.startswith("#/"):
            raise ValueError(f"external reference {ref}")
        cur = doc
        for part in ref[2:].split("/"):
            cur = cur[part]
        node = cur
        seen += 1
        if seen > 32:
            raise ValueError(f"reference cycle at {ref}")
    return node


def camel(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    head, *rest = [p for p in parts if p] or ["op"]
    out = head[0].lower() + head[1:] + "".join(p[0].upper() + p[1:] for p in rest)
    return out if not out[0].isdigit() else "op" + out


def operations(config: dict) -> tuple[list[dict], list[str]]:
    errors: list[str] = []
    manifest = load(ROUTE_MANIFEST)
    paid = {(p.split(" ", 1)[0], p.split(" ", 1)[1]) for p in config["paidTelecomOperations"]}
    docs = {}
    for f in sorted(PUBLIC_DOCS.glob("*/v1.openapi.json")):
        if f.parent.name != "aggregate":
            docs[f.parent.name] = load(f)
    ops: list[dict] = []
    names: dict[tuple[str, str], str] = {}
    found_paid = set()
    for r in manifest["routes"]:
        domain, method, path = r["domain"], r["method"], r["pattern"]
        doc = docs.get(domain)
        node = doc and doc["paths"].get(path, {}).get(method.lower())
        if not node:
            errors.append(f"{method} {path}: routed but not in bundled/public/{domain}")
            continue
        item = doc["paths"][path]
        params = [resolve(doc, x) for x in item.get("parameters", []) + node.get("parameters", [])]
        path_params = [x["name"] for x in params if x["in"] == "path"]
        query = [{"name": x["name"], "required": bool(x.get("required"))} for x in params if x["in"] == "query"]
        headers = [{"name": x["name"].lower(), "required": bool(x.get("required"))}
                   for x in params if x["in"] == "header" and x["name"].lower() != "idempotency-key"]
        idem = next((x for x in params if x["in"] == "header" and x["name"].lower() == "idempotency-key"), None)
        idempotency = "NONE" if idem is None else ("REQUIRED" if idem.get("required") else "OPTIONAL")
        body = node.get("requestBody")
        body = resolve(doc, body) if body else None
        pagination = None
        if method == "GET" and any(q["name"] == "cursor" for q in query):
            ok = next((resolve(doc, v) for k, v in node.get("responses", {}).items() if k.startswith("2")), {})
            schema = resolve(doc, ok.get("content", {}).get("application/json", {}).get("schema", {}))
            props = schema.get("properties", {}) if isinstance(schema, dict) else {}
            arrays = [k for k, v in props.items() if resolve(doc, v).get("type") == "array"]
            if "nextCursor" in props and len(arrays) == 1:
                pagination = {"cursorParam": "cursor", "nextField": "nextCursor", "itemsField": arrays[0]}
        is_paid = (method, path) in paid
        if is_paid:
            found_paid.add((method, path))
            retry = "NEVER"
        elif method == "GET":
            retry = "SAFE"
        elif method in ("PUT", "DELETE") or idempotency != "NONE":
            retry = "IDEMPOTENT"
        else:
            retry = "NO_RETRY"
        name = camel(node.get("operationId") or r["id"].split(".", 1)[-1])
        key = (domain, name)
        if key in names:
            errors.append(f"{domain}.{name}: duplicate operation name ({names[key]} and {method} {path})")
        names[key] = f"{method} {path}"
        success = sorted(int(k) for k in node.get("responses", {}) if k.isdigit() and k.startswith("2"))
        ops.append({
            "domain": domain, "name": name, "operationId": node.get("operationId", ""), "method": method,
            "path": path, "protocol": r["protocol"], "auth": r["auth"], "scope": r.get("requiredScope"),
            "pathParams": path_params, "query": query, "headers": headers,
            "body": "NONE" if not body else ("REQUIRED" if body.get("required") else "OPTIONAL"),
            "idempotency": idempotency, "retry": retry, "paidTelecom": is_paid, "pagination": pagination,
            "success": success,
        })
    for m, p in paid - found_paid:
        errors.append(f"paidTelecomOperations: {m} {p} is not a routed public operation")
    for m, p in paid:
        if m not in MUTATIONS:
            errors.append(f"paidTelecomOperations: {m} {p} is not a mutation")
    ops.sort(key=lambda o: (o["domain"], o["name"]))
    return ops, errors


def ts_operations(ops: list[dict]) -> str:
    lines = [f"// {HEADER.replace('packages/contracts/manifest.json', 'the public API documents and the gateway route manifest')}", "",
             "export type RetryClass = 'SAFE' | 'IDEMPOTENT' | 'NO_RETRY' | 'NEVER';",
             "export type AuthMode = string;", "",
             "export interface ParamSpec {", "  readonly name: string;", "  readonly required: boolean;", "}", "",
             "export interface PaginationSpec {", "  readonly cursorParam: string;", "  readonly nextField: string;",
             "  readonly itemsField: string;", "}", "",
             "export interface OperationSpec {", "  readonly domain: string;", "  readonly name: string;",
             "  readonly operationId: string;", "  readonly method: 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE';",
             "  readonly path: string;", "  readonly protocol: 'REST' | 'WEBSOCKET';", "  readonly auth: readonly AuthMode[];",
             "  readonly scope: string | null;", "  readonly pathParams: readonly string[];",
             "  readonly query: readonly ParamSpec[];", "  readonly headers: readonly ParamSpec[];",
             "  readonly body: 'NONE' | 'OPTIONAL' | 'REQUIRED';", "  readonly idempotency: 'NONE' | 'OPTIONAL' | 'REQUIRED';",
             "  readonly retry: RetryClass;", "  readonly paidTelecom: boolean;",
             "  readonly pagination: PaginationSpec | null;", "  readonly success: readonly number[];", "}", "",
             "export const OPERATIONS: readonly OperationSpec[] = ["]
    for o in ops:
        lines.append("  " + json.dumps(o, ensure_ascii=False, separators=(", ", ": ")) + ",")
    lines += ["];", ""]
    return "\n".join(lines)


def dart_str(v) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, str):
        return "'" + v.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"
    if isinstance(v, list):
        return "<Object?>[" + ", ".join(dart_str(x) for x in v) + "]" if v and not all(isinstance(x, str) for x in v) else "<String>[" + ", ".join(dart_str(x) for x in v) + "]"
    raise TypeError(v)


def dart_operations(ops: list[dict]) -> str:
    lines = [f"// {HEADER.replace('packages/contracts/manifest.json', 'the public API documents and the gateway route manifest')}", "",
             "import '../operation.dart';", "", "const List<OperationSpec> operations = <OperationSpec>["]
    for o in ops:
        params = lambda xs: "<ParamSpec>[" + ", ".join(f"ParamSpec({dart_str(x['name'])}, required: {dart_str(x['required'])})" for x in xs) + "]"
        pag = "null" if not o["pagination"] else (
            f"PaginationSpec(cursorParam: {dart_str(o['pagination']['cursorParam'])}, nextField: {dart_str(o['pagination']['nextField'])}, itemsField: {dart_str(o['pagination']['itemsField'])})")
        lines.append(
            "  OperationSpec("
            f"domain: {dart_str(o['domain'])}, name: {dart_str(o['name'])}, operationId: {dart_str(o['operationId'])}, "
            f"method: {dart_str(o['method'])}, path: {dart_str(o['path'])}, protocol: {dart_str(o['protocol'])}, "
            f"auth: {dart_str(o['auth'])}, scope: {dart_str(o['scope'])}, pathParams: {dart_str(o['pathParams'])}, "
            f"query: {params(o['query'])}, headers: {params(o['headers'])}, body: {dart_str(o['body'])}, "
            f"idempotency: {dart_str(o['idempotency'])}, retry: RetryClass.{ {'SAFE': 'safe', 'IDEMPOTENT': 'idempotent', 'NO_RETRY': 'noRetry', 'NEVER': 'never'}[o['retry']]}, "
            f"paidTelecom: {dart_str(o['paidTelecom'])}, pagination: {pag}, success: <int>[{', '.join(map(str, o['success']))}]),")
    lines += ["];", ""]
    return "\n".join(lines)


# ---------------------------------------------------------------------------------------
# TypeScript models (additive emitter): one namespace per public domain document with a
# type for every component schema, plus `Operations` — the typed request parameters and
# response of every REST operation of the domain (WebSocket operations are excluded; the
# SDK's realtime helpers own them). JSON Schema keywords that only constrain values
# (pattern, bounds, not, if / then / else, propertyNames) have no TypeScript counterpart
# and are ignored; descriptions that name a product are omitted (product-name guard).

TS_DOMAIN_NAMESPACE = {
    "calling": "Calling", "developer-platform": "DeveloperPlatform", "gateway": "Gateway",
    "meetings": "Meetings", "messaging": "Messaging", "numbering": "Numbering",
    "privacy-relay": "PrivacyRelay", "sms": "Sms",
}
TS_IDENT_RE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
TS_CONSTRAINT_KEYS = {"required", "not", "description", "title", "if", "then", "else", "$comment",
                      "minProperties", "maxProperties", "examples", "example", "deprecated"}


def ts_pascal(segment: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", segment) if p)


def ts_model_names(names: list[str]) -> dict[str, str]:
    """Shortest unique, readable identifier per schema name (`a.common.v1.Call` → `Call`)."""
    segs = {n: [s for s in n.split(".") if s] for n in names}
    useful = {n: [s for s in segs[n][:-1] if not re.fullmatch(r"v\d+", s)] for n in names}
    depth = {n: 0 for n in names}

    def ident(n: str) -> str:
        parts = useful[n][len(useful[n]) - depth[n]:] if depth[n] else []
        out = "".join(ts_pascal(p) for p in parts + [segs[n][-1]]) or "Schema"
        out = out if TS_IDENT_RE.match(out) and not out[0].isdigit() else "S" + out
        return out

    while True:
        groups: dict[str, list[str]] = {}
        for n in names:
            groups.setdefault(ident(n), []).append(n)
        clashes = [g for g in groups.values() if len(g) > 1]
        if not clashes:
            return {n: ident(n) for n in names}
        progressed = False
        for g in clashes:
            for n in g:
                if depth[n] < len(useful[n]):
                    depth[n] += 1
                    progressed = True
        if not progressed:
            raise ValueError(f"cannot name schemas uniquely: {clashes}")


def ts_doc(text, indent: str) -> list[str]:
    if not isinstance(text, str) or not text.strip() or PRODUCT_RE.search(text):
        return []
    para = " ".join(text.strip().split("\n\n")[0].split())
    if len(para) > 400:
        para = para[:399].rsplit(" ", 1)[0] + " …"
    para = para.replace("*/", "*\\/")
    return [f"{indent}/** {para} */"]


def ts_key(name: str) -> str:
    return name if TS_IDENT_RE.match(name) else json.dumps(name)


class TsModels:
    def __init__(self, doc: dict):
        self.doc = doc
        self.schemas = doc.get("components", {}).get("schemas", {})
        self.names = ts_model_names(list(self.schemas))

    def ref(self, ref: str, depth: int) -> str:
        prefix = "#/components/schemas/"
        if ref.startswith(prefix) and ref[len(prefix):] in self.schemas:
            return self.names[ref[len(prefix):]]
        return self.type(resolve(self.doc, {"$ref": ref}), depth + 1)

    def type(self, s, depth: int = 0) -> str:
        if depth > 48:
            return "unknown"
        if s is True or s is None:
            return "unknown"
        if s is False:
            return "never"
        if not isinstance(s, dict):
            return "unknown"
        parts: list[str] = []
        if "$ref" in s:
            parts.append(self.ref(s["$ref"], depth))
        if "const" in s:
            parts.append(json.dumps(s["const"], ensure_ascii=False))
        elif "enum" in s:
            parts.append(" | ".join(json.dumps(v, ensure_ascii=False) for v in s["enum"]) or "never")
        else:
            base = self.base(s, depth)
            if base is not None:
                parts.append(base)
        for kw in ("oneOf", "anyOf"):
            if kw in s:
                parts.append(self.union(s, s[kw], depth))
        for member in s.get("allOf", []):
            t = self.member(s, member, depth)
            if t is not None:
                parts.append(t)
        if not parts:
            return "unknown"
        out = parts[0] if len(parts) == 1 else " & ".join(f"({p})" for p in parts)
        if s.get("nullable") is True:
            out = f"({out}) | null"
        return out

    def member(self, parent: dict, m, depth: int):
        """An allOf / oneOf / anyOf member; constraint-only members (required, not, if...)
        refine the parent's properties instead of standing alone."""
        if isinstance(m, dict) and m and set(m) <= TS_CONSTRAINT_KEYS | {"properties"} and "type" not in m:
            req = [r for r in m.get("required", []) if isinstance(r, str)]
            props = {**parent.get("properties", {}), **m.get("properties", {})}
            if not req:
                return None
            fields = "; ".join(f"{ts_key(r)}: {self.type(props.get(r, True), depth + 1)}" for r in req)
            return "{ " + fields + " }"
        return self.type(m, depth + 1)

    def union(self, parent: dict, members: list, depth: int) -> str:
        out = []
        for m in members:
            t = self.member(parent, m, depth)
            out.append("{}" if t is None else t)
        uniq = list(dict.fromkeys(out))
        return " | ".join(f"({t})" if (" & " in t or " | " in t) else t for t in uniq) or "never"

    def base(self, s: dict, depth: int):
        t = s.get("type")
        if isinstance(t, list):
            alts = [self.single(s, x, depth) for x in t]
            alts = [a for a in dict.fromkeys(alts) if a is not None]
            return " | ".join(f"({a})" if " & " in a else a for a in alts) if alts else None
        if t is None:
            if "properties" in s or "additionalProperties" in s:
                return self.single(s, "object", depth)
            if "items" in s or "prefixItems" in s:
                return self.single(s, "array", depth)
            return None
        return self.single(s, t, depth)

    def single(self, s: dict, t: str, depth: int):
        if t == "string":
            return "string"
        if t in ("integer", "number"):
            return "number"
        if t == "boolean":
            return "boolean"
        if t == "null":
            return "null"
        if t == "array":
            items = s.get("items")
            inner = self.type(items, depth + 1) if items is not None else "unknown"
            return f"Array<{inner}>"
        if t == "object":
            return self.object(s, depth)
        return "unknown"

    def object(self, s: dict, depth: int) -> str:
        props = s.get("properties", {})
        required = [r for r in s.get("required", []) if isinstance(r, str)]
        ap = s.get("additionalProperties", None)
        indent = "  " * (depth + 2)
        lines: list[str] = []
        for name, sub in props.items():
            lines += ts_doc(sub.get("description") if isinstance(sub, dict) else None, indent)
            opt = "" if name in required else "?"
            lines.append(f"{indent}{ts_key(name)}{opt}: {self.type(sub, depth + 1)};")
        for r in required:
            if r not in props:
                lines.append(f"{indent}{ts_key(r)}: unknown;")
        body = "{\n" + "\n".join(lines) + "\n" + "  " * (depth + 1) + "}" if lines else None
        if ap is None or ap is True:
            index = None if props else "{ [key: string]: unknown }"
        elif ap is False:
            index = None
        else:
            index = "{ [key: string]: " + self.type(ap, depth + 1) + " }"
        if body and index:
            return f"{body} & {index}"
        return body or index or "{ [key: string]: never }"

    def response(self, node: dict) -> str:
        out = []
        for code, r in sorted(node.get("responses", {}).items()):
            if not (code.isdigit() and code.startswith("2")):
                continue
            r = resolve(self.doc, r)
            content = r.get("content", {})
            if "application/json" in content:
                out.append(self.type(content["application/json"].get("schema", True), 1))
            elif content:
                out.append("ArrayBuffer")
            else:
                out.append("void")
        uniq = list(dict.fromkeys(out)) or ["void"]
        return " | ".join(f"({t})" if " & " in t else t for t in uniq)


def ts_models(ops: list[dict]) -> str:
    docs = {f.parent.name: load(f) for f in sorted(PUBLIC_DOCS.glob("*/v1.openapi.json")) if f.parent.name != "aggregate"}
    head = HEADER.replace("packages/contracts/manifest.json", "the public API documents (packages/contracts/bundled/public)")
    lines = [f"// {head}", "//",
             "// One namespace per public domain: a type per component schema and `Operations`, the",
             "// typed parameters / response of every REST operation (see client.ts for how they are used).",
             "/* eslint-disable */", ""]
    domain_map = []
    for domain in sorted(docs):
        ns = TS_DOMAIN_NAMESPACE.get(domain) or ts_pascal(domain)
        doc = docs[domain]
        m = TsModels(doc)
        lines.append(f"export namespace {ns} {{")
        for name in sorted(m.schemas, key=lambda n: m.names[n]):
            schema = m.schemas[name]
            lines += ts_doc(schema.get("description") if isinstance(schema, dict) else None, "  ")
            lines.append(f"  export type {m.names[name]} = {m.type(schema, 0)};")
        lines.append("")
        lines.append("  /** Typed parameters and response of every REST operation of this domain. */")
        lines.append("  export interface Operations {")
        for o in (o for o in ops if o["domain"] == domain and o["protocol"] == "REST"):
            node = doc["paths"][o["path"]][o["method"].lower()]
            item = doc["paths"][o["path"]]
            params = [resolve(doc, x) for x in item.get("parameters", []) + node.get("parameters", [])]
            by_in = lambda where: [p for p in params if p["in"] == where and p["name"].lower() != "idempotency-key"]
            fields = []
            for where, key in (("path", "path"), ("query", "query"), ("header", "headers")):
                ps = by_in(where)
                if not ps:
                    continue
                names = [p["name"].lower() if where == "header" else p["name"] for p in ps]
                inner = "; ".join(
                    f"{ts_key(n)}{'' if p.get('required') or where == 'path' else '?'}: {m.type(p.get('schema', {'type': 'string'}), 3)}"
                    for n, p in zip(names, ps))
                req = where == "path" or any(p.get("required") for p in ps)
                fields.append(f"{key}{'' if req else '?'}: {{ {inner} }}")
            body = node.get("requestBody")
            if body:
                body = resolve(doc, body)
                content = body.get("content", {})
                bt = m.type(content["application/json"].get("schema", True), 3) if "application/json" in content else "unknown"
                fields.append(f"body{'' if body.get('required') else '?'}: {bt}")
            if o["idempotency"] != "NONE":
                fields.append("idempotencyKey?: string")
            summary = f"{o['method']} {o['path']}" + (f" — scope {o['scope']}" if o["scope"] else "") + \
                      f"; auth {' | '.join(o['auth'])}; retry {o['retry']}" + ("; paid telecom" if o["paidTelecom"] else "")
            lines.append(f"    /** {summary} */")
            lines.append(f"    {ts_key(o['name'])}: {{")
            lines.append("      params: {" + (" " + "; ".join(fields) + " " if fields else "") + "};")
            response = m.response(node)
            lines.append(f"      response: {response};")
            if o["pagination"]:
                lines.append(f"      item: NonNullable<({response})[{json.dumps(o['pagination']['itemsField'])}]>[number];")
            lines.append("    };")
        lines.append("  }")
        lines.append("}")
        lines.append("")
        domain_map.append((domain, ns))
    lines.append("/** Operation types of every domain, keyed like `OperationSpec.domain`. */")
    lines.append("export interface DomainOperations {")
    for domain, ns in domain_map:
        lines.append(f"  {ts_key(domain)}: {ns}.Operations;")
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    check = "--check" in argv
    config = load(HERE / "generation.json")
    manifest = load(ROOT / "packages/contracts/manifest.json")
    cat, errors = catalogue(config, manifest)
    ops, op_errors = operations(config)
    errors += op_errors
    if PRODUCT_RE.search((HERE / "generation.json").read_text(encoding="utf-8")):
        errors.append("sdks/generation.json: names a product")
    for sdk in ("typescript", "dart"):
        for f in (HERE / sdk).rglob("*"):
            if f.is_file() and "node_modules" not in f.parts and PRODUCT_RE.search(f.read_text(encoding="utf-8", errors="ignore")):
                errors.append(f"{f.relative_to(ROOT)}: names a product")
    outputs = {
        HERE / config["typescript"]["output"]: typescript(cat, config["status"]),
        HERE / config["dart"]["output"]: dart(cat, config["status"]),
        HERE / config["typescript"]["operations"]: ts_operations(ops),
        HERE / config["dart"]["operations"]: dart_operations(ops),
    }
    if config["typescript"].get("models"):
        outputs[HERE / config["typescript"]["models"]] = ts_models(ops)
    for path, text in outputs.items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                errors.append(f"{path.relative_to(ROOT)}: stale or missing; run python3 sdks/generate.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    for e in errors:
        print(f"sdks: {e}")
    if errors:
        print(f"sdks: FAILED — {len(errors)} problem(s)", file=sys.stderr)
        return 1
    print(f"sdks: OK — {len(ops)} operation(s) ({sum(o['paidTelecom'] for o in ops)} paid telecom, never auto-retried); {len(cat)} contract(s) pinned for {config['typescript']['package']} and {config['dart']['package']} ({config['status']})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
