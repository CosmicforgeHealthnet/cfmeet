#!/usr/bin/env python3
"""Migration naming and ordering guard (DATA-014).

SeaORM runs migrations in the order of each migrator's ``migrations()`` vector and
records each one in that migrator's history table under its name (an explicit
``MigrationName::name()``, otherwise the module name). Names that do not sort in
vector order (a migration generated today after a future-dated one) or odd names
make review and history reconciliation error-prone. For every
``impl MigratorTrait`` in ``services/*/migration/src/lib.rs`` this guard checks:

1. every entry is named ``m<YYYYMMDD>_<NNNNNN>_<snake_case>`` with a real date and
   no second ``m<YYYYMMDD>_`` prefix inside the name;
2. entries sort strictly ascending in vector order, so a new migration must be
   appended at the end AND sort last (pick a date/sequence after the last entry,
   even if that date is in the future);
3. a name appears in only one migrator of the crate (one history owns it).

Anomalies that already exist in applied histories cannot be renamed safely (the
name is the history key), so they are frozen in ``BASELINE`` below; anything not
in the baseline fails. Standard library only.
"""
from __future__ import annotations

import datetime
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NAME = re.compile(r"^m(\d{8})_(\d{6})_([a-z0-9]+(?:_[a-z0-9]+)*)$")
ENTRY = re.compile(r"Box::new\(\s*((?:[A-Za-z_]\w*::)*[A-Za-z_]\w*)\s*,?\s*\)")
IMPL = re.compile(r"impl\s+MigratorTrait\s+for\s+(\w+)\s*\{")
EXPLICIT = re.compile(r"impl\s+MigrationName\s+for\s+(\w+)\s*\{[^}]*?fn\s+name\s*\([^)]*\)[^{]*\{\s*\"([^\"]+)\"", re.S)

# (crate, migrator, history name, rule) of anomalies already recorded in applied
# histories. Never add an entry for a new migration: rename the new migration instead.
BASELINE: set[tuple[str, str, str, str]] = {
    # Separate Communications histories keyed by their module name (Section 2 era).
    ("calling", "CommunicationsMigrator", "communications", "name"),
    ("messaging", "CommunicationsMigrator", "communications", "name"),
    # Generated by sea-orm-cli on top of an already-prefixed name.
    ("meeting-service", "Migrator", "m20260205_110126_m20260205_000001_add_guest_role", "double-prefix"),
}


def strip_line_comments(text: str) -> str:
    return re.sub(r"//[^\n]*", "", text)


def balanced_block(text: str, open_brace: int) -> str:
    depth = 0
    for i in range(open_brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_brace + 1 : i]
    return text[open_brace + 1 :]


def history_name(src: Path, lib_text: str, path: str) -> str:
    """The name SeaORM records for one `Box::new(...)` entry."""
    parts = path.split("::")
    if parts[-1] == "Migration" and len(parts) >= 2:
        module = parts[-2]
        file = src / f"{module}.rs"
        if file.is_file():
            return dict(EXPLICIT.findall(file.read_text(encoding="utf-8"))).get("Migration", module)
        return module
    return dict(EXPLICIT.findall(lib_text)).get(parts[-1], parts[-1])


def migrators(lib: Path) -> dict[str, list[str]]:
    text = strip_line_comments(lib.read_text(encoding="utf-8"))
    out: dict[str, list[str]] = {}
    for m in IMPL.finditer(text):
        body = balanced_block(text, m.end() - 1)
        fn = re.search(r"fn\s+migrations\s*\(\s*\)", body)
        if not fn:
            continue
        fn_body = balanced_block(body, body.index("{", fn.end()))
        out[m.group(1)] = [history_name(lib.parent, text, e) for e in ENTRY.findall(fn_body)]
    return out


def problems_of(crate: str, found: dict[str, list[str]]) -> list[tuple[str, str, str, str, str]]:
    """[(crate, migrator, name, rule, message)]"""
    out = []
    owner: dict[str, str] = {}
    for migrator, names in found.items():
        previous = None
        for name in names:
            m = NAME.match(name)
            if not m:
                out.append((crate, migrator, name, "name", "is not m<YYYYMMDD>_<NNNNNN>_<snake_case>"))
            else:
                try:
                    datetime.datetime.strptime(m.group(1), "%Y%m%d")
                except ValueError:
                    out.append((crate, migrator, name, "date", f"has an invalid date {m.group(1)}"))
                if re.search(r"(?:^|_)m\d{8}_", m.group(3)):
                    out.append((crate, migrator, name, "double-prefix", "repeats an m<YYYYMMDD>_ prefix inside the name"))
            if previous is not None and name <= previous:
                out.append((crate, migrator, name, "order", f"does not sort after the previous entry {previous}; append new migrations with a name that sorts last"))
            previous = name
            if name in owner and owner[name] != migrator:
                out.append((crate, migrator, name, "duplicate", f"is also run by {owner[name]}"))
            owner.setdefault(name, migrator)
        if not names:
            out.append((crate, migrator, "-", "empty", "migrations() lists no entries this guard can read"))
    return out


def main() -> int:
    libs = sorted(ROOT.glob("services/*/migration/src/lib.rs"))
    if not libs:
        print("FAIL: no migration crates found")
        return 1
    failures, used, total = [], set(), 0
    for lib in libs:
        crate = lib.parts[-4]
        found = migrators(lib)
        if not found:
            failures.append(f"{crate}: no MigratorTrait implementation found in {lib.relative_to(ROOT)}")
        total += sum(len(v) for v in found.values())
        for c, migrator, name, rule, message in problems_of(crate, found):
            if (c, migrator, name, rule) in BASELINE:
                used.add((c, migrator, name, rule))
                continue
            failures.append(f"{c} {migrator}: {name} {message}")
    for f in failures:
        print(f"FAIL: {f}")
    stale = sorted(BASELINE - used)
    for b in stale:
        print(f"FAIL: baseline entry no longer matches anything (remove it): {b}")
    if failures or stale:
        return 1
    print(f"PASS: {total} migrations in {len(libs)} crates are well named and append-ordered ({len(used)} frozen historical anomalies).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
