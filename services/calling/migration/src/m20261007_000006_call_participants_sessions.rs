//! Call participants, call sessions and session connection intervals (Part C §19).
//!
//! ```text
//! Call ─┬─ CallParticipant  (logical identity: one trusted principal, role, permissions)
//!       │      └─ CallSession (one device / network participation: server-generated
//!       │             │        media identity, endpoint category, connection state)
//!       │             └─ CallSessionInterval (one connected period: n = 1, 2, … reconnects)
//! ```
//!
//! * A participant is a logical communication participant, never a connection. A principal
//!   is represented by exactly one participant per Call (`UNIQUE (call_id, principal_id)`),
//!   so reconnects and additional devices can never create a second logical participant.
//!   The principal reference and its kind snapshot are pinned by composite foreign key to
//!   a principal of the Call's own tenant / application / environment.
//! * A participant may own many sessions at the same time (multi-device); there is
//!   deliberately no uniqueness on `participant_id`. The media identity is generated by
//!   the server (`cfmid_` + 256 random bits), globally unique and provider-neutral.
//! * Connection time is recorded as intervals: one open interval per session (partial
//!   unique index), gap-free increasing interval numbers, no overlap, closed intervals
//!   are never reopened (trigger-enforced). Participation time is computed from intervals,
//!   never from a single join / leave pair.
//! * Display names are presentation metadata: bounded, trimmed, no control characters and
//!   no telephone-number-like content. They never identify or authorize anyone.

