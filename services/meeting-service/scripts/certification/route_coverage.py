#!/usr/bin/env python3
"""Part M route coverage report.

Joins the runtime request records written by the integration-test harness
(tests/common/route_coverage.rs → $CARGO_TARGET_TMPDIR/route-coverage/*.tsv) with the
OpenAPI contract and reports, for every `/api/v2` operation, whether at least one test
exercised a success path (2xx / 101) and an error path (4xx / 5xx).

Usage:
  route_coverage.py [--records DIR] [--openapi FILE] [--json OUT] [--markdown OUT] [--strict]

--strict exits 1 when any operation lacks a success-path or an error-path hit.
"""
import argparse
import collections
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SERVICE = os.path.abspath(os.path.join(HERE, "..", ".."))


def normalize(path: str) -> str:
    return "/".join(
        "{}" if seg.startswith(":") or (seg.startswith("{") and seg.endswith("}")) else seg
        for seg in path.split("/")
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--records", default=os.path.join(SERVICE, "target", "tmp", "route-coverage"))
    ap.add_argument(
        "--openapi",
        default=os.path.join(SERVICE, "..", "..", "packages", "contracts", "openapi", "meeting-service.json"),
    )
    ap.add_argument("--json")
    ap.add_argument("--markdown")
    ap.add_argument("--strict", action="store_true")
    a = ap.parse_args()

    doc = json.load(open(a.openapi))
    ops = []
    for path, item in doc["paths"].items():
        if not path.startswith("/api/v2"):
            continue
        for method, op in item.items():
            ops.append((method.upper(), path, op.get("operationId", "")))

    hits = collections.defaultdict(lambda: {"success": 0, "error": 0, "statuses": collections.Counter(), "tests": set()})
    files = glob.glob(os.path.join(a.records, "*.tsv"))
    if not files:
        print(f"no route records under {a.records}; run the integration suite first", file=sys.stderr)
        return 2
    for f in files:
        suite = re.sub(r"-[0-9a-f]{16}-\d+\.tsv$", "", os.path.basename(f))
        suite = re.sub(r"-\d+\.tsv$", "", suite)
        for line in open(f, errors="replace"):
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3 or not parts[1]:
                continue
            method, route, status = parts[0], parts[1], int(parts[2])
            key = (method, normalize(route))
            h = hits[key]
            h["statuses"][status] += 1
            if 200 <= status < 300 or status == 101:
                h["success"] += 1
            elif status >= 400:
                h["error"] += 1
            test = parts[3] if len(parts) > 3 else ""
            h["tests"].add(f"{suite}::{test}" if test else suite)

    rows = []
    for method, path, op_id in sorted(ops, key=lambda o: (o[1], o[0])):
        h = hits.get((method, normalize(path)), {"success": 0, "error": 0, "statuses": {}, "tests": set()})
        rows.append(
            {
                "method": method,
                "path": path,
                "operationId": op_id,
                "successHits": h["success"],
                "errorHits": h["error"],
                "statuses": dict(sorted(h["statuses"].items())),
                "testCount": len(h["tests"]),
                "status": "COVERED" if h["success"] and h["error"] else ("PARTIAL" if h["success"] or h["error"] else "NOT COVERED"),
            }
        )
    covered = sum(r["status"] == "COVERED" for r in rows)
    summary = {
        "operations": len(rows),
        "covered": covered,
        "partial": sum(r["status"] == "PARTIAL" for r in rows),
        "notCovered": sum(r["status"] == "NOT COVERED" for r in rows),
        "recordFiles": len(files),
        "requestsRecorded": sum(sum(h["statuses"].values()) for h in hits.values()),
    }
    print(json.dumps(summary))
    for r in rows:
        if r["status"] != "COVERED":
            print(f'{r["status"]}: {r["method"]} {r["path"]} statuses={r["statuses"]}')
    if a.json:
        json.dump({"summary": summary, "operations": rows}, open(a.json, "w"), indent=2)
    if a.markdown:
        with open(a.markdown, "w") as out:
            out.write("# `/api/v2` route coverage (measured)\n\n")
            out.write(
                "Generated by `scripts/certification/route_coverage.py` from the requests the "
                "integration suites actually sent (`tests/common/route_coverage.rs`).\n\n"
            )
            out.write(
                f"- operations: {summary['operations']}\n- success + error path covered: {summary['covered']}\n"
                f"- partially covered: {summary['partial']}\n- not covered: {summary['notCovered']}\n"
                f"- requests recorded: {summary['requestsRecorded']}\n\n"
            )
            out.write("| Method | Path | Success hits | Error hits | Status codes seen | Tests | Status |\n")
            out.write("|---|---|---:|---:|---|---:|---|\n")
            for r in rows:
                codes = ", ".join(f"{k}×{v}" for k, v in r["statuses"].items())
                out.write(
                    f'| {r["method"]} | `{r["path"]}` | {r["successHits"]} | {r["errorHits"]} | {codes} | {r["testCount"]} | {r["status"]} |\n'
                )
    if a.strict and covered != len(rows):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
